"""Builds lean-towns-data.js: where each town's warehouse, potion merchant, repair merchant and world statue stand.

Usage: python gen-towns.py <server textdata folder> [output file]
Reads npcpos.txt, characterdata_*.txt, teleportbuilding.txt and teleportdata.txt (UTF-16). Positions are region-local, as the game sends them.
"""
import glob
import json
import math
import sys
from pathlib import Path

folder = Path(sys.argv[1])
out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).with_name('lean-towns-data.js')

def rows(name):
    for line in open(folder / name, encoding='utf-16', errors='ignore'):
        yield line.rstrip('\r\n').split('\t')

names = {}
for path in sorted(glob.glob(str(folder / 'characterdata_*.txt'))):
    for c in rows(Path(path).name):
        if len(c) > 3 and c[1].isdigit():
            names[int(c[1])] = c[2]

def world(region, x, z):
    return ((region & 255) - 135) * 1920 + x, ((region >> 8) - 92) * 1920 + z

# NPC_<town>_<SERVICE>[_n]: KT Hotan, CH Jangan, WC Donwhang, EU Constantinople, CA Samarkand.
SERVICES = {'WAREHOUSE': 'storage', 'POTION': 'vendor', 'SMITH': 'smith'}
# The specialty (trade goods) merchant is optional: SPECIAL2 stands in a different area and is left out.
TRADE = 'SPECIAL'
found = {}
for c in rows('npcpos.txt'):
    if len(c) < 5:
        continue
    npc, region = int(c[0]), int(c[1])
    parts = names.get(npc, '').split('_')
    if len(parts) < 3 or parts[0] != 'NPC' or (parts[2] not in SERVICES and parts[2] != TRADE):
        continue
    found.setdefault(parts[1], {}).setdefault(SERVICES.get(parts[2], 'trade'), []).append(
        {'refObjId': npc, 'regionId': region, 'x': round(float(c[2]), 2), 'y': round(float(c[3]), 2), 'z': round(float(c[4]), 2)})

gates = {}
for c in rows('teleportbuilding.txt'):
    k = next((i for i, t in enumerate(c) if t.startswith('FORTRESS_')), None)
    parts = c[2].split('_') if len(c) > 2 else []
    if k and len(parts) == 3 and parts[0] == 'STORE' and parts[2] == 'GATE':
        gates[parts[1]] = {'name': c[k][len('FORTRESS_'):].title(), 'refObjId': int(c[1]), 'regionId': int(c[k - 14]),
                           'x': float(c[k - 12]), 'y': float(c[k - 11]), 'z': float(c[k - 10])}

# Where a return scroll puts you: the town gate's recall destination (teleportdata GATE_<town>, recall flag set).
arrivals = {}
for c in rows('teleportdata.txt'):
    if len(c) > 10 and c[2].startswith('GATE_') and c[10] == '1':
        arrivals[c[2][len('GATE_'):]] = {'regionId': int(c[5]), 'x': float(c[6]), 'y': float(c[7]), 'z': float(c[8])}

towns = []
for key, gate in sorted(gates.items(), key=lambda kv: kv[1]['name']):
    svc = found.get(key, {})
    if not all(svc.get(role) for role in SERVICES.values()) or key not in arrivals:
        continue
    # Two warehouses or potion stalls in a town: take the one nearest the repair merchant.
    smith = svc['smith'][0]
    def near(e):
        a, b = world(e['regionId'], e['x'], e['z']), world(smith['regionId'], smith['x'], smith['z'])
        return math.dist(a, b)
    services = {role: min(svc[role], key=near) for role in ('storage', 'vendor')}
    services['smith'] = smith
    if svc.get('trade'):
        services['trade'] = svc['trade'][0]
    # The statue's recorded height is not the ground height; use the warehouse's.
    services['gate'] = {**gate, 'y': services['storage']['y']}
    del services['gate']['name']
    towns.append({'key': key, 'name': gate['name'], 'arrival': arrivals[key], 'services': services})

text = '// Generated by gen-towns.py from the server data. Do not edit by hand.\nconst TOWN_TABLE = ' + json.dumps(towns, separators=(',', ':')) + ';\n'
out.write_text(text, encoding='utf-8', newline='\n')
for t in towns:
    regions = sorted({s['regionId'] for s in t['services'].values()})
    print(t['name'], t['key'], 'regions', regions)
